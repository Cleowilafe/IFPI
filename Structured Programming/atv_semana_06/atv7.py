#Entrada de dados
idade = float(input("Digite um valor: "))

#Processamento de dados

def idad(idade):
    anos = round(idade)
    return anos

def main():
    anos = idad(idade)
    
    #Saída de dados
    print(f"O valor arredondado é: {anos}")

if __name__ == "__main__":
    main()
